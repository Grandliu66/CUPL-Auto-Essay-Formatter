def main() -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "样式判定与操作逻辑"

    for col, head in enumerate(HEADERS, start=1):
        cell = ws.cell(row=1, column=col, value=head)
        cell.font = Font(name="微软雅黑", size=11, bold=True)
        cell.fill = HEAD_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.row_dimensions[1].height = 26

    for r, row in enumerate(ROWS, start=2):
        for col, value in enumerate(row, start=1):
            cell = ws.cell(row=r, column=col, value=value)
            cell.font = Font(name="微软雅黑", size=10,
                             bold=(col == 2))
            cell.alignment = Alignment(vertical="top", wrap_text=True,
                                       horizontal="center" if col == 1 else "left")
            cell.fill = ZONE_FILL.get(row[0], PatternFill("solid", fgColor="FFFFFF"))
            cell.border = BORDER
        ws.row_dimensions[r].height = None      # 交给 Excel 按内容自动撑高

    for col, width in zip(range(1, len(HEADERS) + 1), (12, 18, 62, 52, 74)):
        ws.column_dimensions[get_column_letter(col)].width = width
    ws.freeze_panes = "C2"
    ws.sheet_view.zoomScale = 90

    ws2 = wb.create_sheet("总则与顺序")
    ws2.column_dimensions["A"].width = 26
    ws2.column_dimensions["B"].width = 120
    for r, (a, b) in enumerate(NOTES, start=1):
        ca = ws2.cell(row=r, column=1, value=a)
        cb = ws2.cell(row=r, column=2, value=b)
        bold = bool(a) and not b
        ca.font = Font(name="微软雅黑", size=11, bold=bold)
        cb.font = Font(name="微软雅黑", size=10)
        cb.alignment = Alignment(vertical="top", wrap_text=True)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUT)
    print(f"已生成：{OUT}")


