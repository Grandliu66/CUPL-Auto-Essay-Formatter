def digest(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def main() -> None:
    if not TARGET.exists():
        print(f"找不到 {TARGET}")
        sys.exit(1)
    mirror_same = MIRROR.exists() and digest(MIRROR) == digest(TARGET)
    # 备份**不覆盖已有那份**：第一次跑存下的才是用户改动前的原始版本。
    backup = BACKUP
    n = 2
    while backup.exists():
        backup = BACKUP.with_name(f"{BACKUP.stem}-{n}{BACKUP.suffix}")
        n += 1
    shutil.copy2(TARGET, backup)
    print(f"改前版本已备份：{backup.relative_to(ROOT)}")

    book = openpyxl.load_workbook(TARGET)
    for sheet_name, rows in DELETE_ROWS.items():
        sheet = book[sheet_name]
        for row in sorted(rows, reverse=True):
            if sheet.max_row >= row:
                sheet.delete_rows(row, 1)
                print(f"已删掉 {sheet_name} 第 {row} 行（本轮不再新增行）")
    changed: list[tuple[str, str]] = []
    problems: list[str] = []
    for sheet_name, coord, old, new in OPS + OUTLINE_OPS:
        sheet = book[sheet_name]
        cell = sheet[coord]
        value = cell.value
        if old is None:
            if str(value) == new:
                continue                      # 已经改过了（幂等）
            cell.value = new
        elif old == "":
            # 要求这一格本来是空的
            if value is not None and str(value).strip():
                if new in str(value):
                    continue                  # 已经改过了
                problems.append(f"{sheet_name}!{coord} 不是空的，原本是：{str(value)[:40]!r}")
                continue
            cell.value = new
        else:
            text = "" if value is None else str(value)
            if new and new in text:
                continue                      # 已经改过了（幂等）
            if old not in text:
                problems.append(f"{sheet_name}!{coord} 里找不到片段：{old!r}")
                continue
            cell.value = text.replace(old, new)
        cell.fill = YELLOW
        changed.append((f"{sheet_name}!{coord}", str(cell.value).replace("\n", "⏎")))

    if problems:
        print("\n⚠ 有没落到实处的改动：")
        for item in problems:
            print("   " + item)
    print(f"\n改了 {len(changed)} 个单元格：")
    for coord, text in changed:
        print(f"  {coord:<14} {text[:88]}")

    book.save(TARGET)
    print(f"\n已写回 {TARGET.relative_to(ROOT)}")
    if mirror_same:
        shutil.copy2(TARGET, MIRROR)
        print(f"docs/ 那份镜像改前与 reference/ 完全一致，已一并更新")
    elif MIRROR.exists():
        print(f"⚠ docs/ 那份镜像与 reference/ 不一致（被单独改过？），这次只动了 reference/")
    if problems:
        sys.exit(2)


if __name__ == "__main__":
    main()
