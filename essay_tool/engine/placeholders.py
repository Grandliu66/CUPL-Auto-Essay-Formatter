"""工具**自己插进文档的占位语**——单一出处，别处一律从这里取。

为什么单开一个模块：占位语有两个身份，两边必须看同一份定义。

* 它是**给用户看的提示**：`apply_structure` 往"缺失部件"的位置插它，用户把
  内容填进去（或不要就整段删掉）；
* 它同时是"**这个部件的槽位已经被占了**"的证据：文档回炉（把成品再喂回工具）
  时，识别阶段必须认得出"这行字是我自己插的"，否则会把它当用户内容。实测
  （2026-09-15）：成品回炉时 `detect_english_title()` 把**英文副标题的占位语**
  当成了英文题目，于是"英文副标题缺失"→ 又插一条，每回炉一次就多一行。

`apply_structure` 用它插字、`detect` 用它认字，所以放在这个谁都不依赖的模块里
（`detect` 不能 import `apply_structure`——后者反过来依赖前者，会成环）。

改文案只改这里。README 里说的"那几张提示语表"就是下面这几个字典。
"""

from __future__ import annotations

# 题目/副标题没有"标准答案"可填——题目本身就是内容，没法自动生成一段
# "正确的"题目文字，只能提示用户自己写。这句提示语的措辞是工具行为，不是
# 排版规范的一部分，所以留在代码里，不像其余几个部件的插入文字那样进 Excel。
#
# **这些占位语是用户唯一能看到的"操作说明"**：他打开成品发现某处是空的，
# 看到的就只有这一句话。所以每一条都尽量把规范里**容易踩**的硬要求带上
# （字数、个数、大小写、标点），而不是干吧吧一句"请填写"。
PLACEHOLDER_PROMPTS = {
    "题目": "［请在此处填写中文正标题］",
    "副标题": "［请在此处填写中文副标题］",
}

# 摘要/关键词缺失时，标签能从 Excel 里拿到该写什么字，但内容是论文的
# 实质内容，同样没法自动生成，只能插一句提示占位。
CONTENT_PLACEHOLDER_PROMPTS = {
    "摘要": "［请在此处填写摘要］",
    "关键词": "［请在此处填写 3～5 个关键词，每个之间空两格］",
}

# 英文摘要页 2026-09-14 拆成三个可单独开关的部件：英文题目（S11）、英文摘要
# （摘要标签 S12 + 英文摘要内容 S13）、英文关键词（关键词标签 S30 + 英文关键词
# 内容 S31）。各自要不要补由 `_insert_missing_part` 单独判断；页序靠
# `_FRONT_ORDER` 的顺序（`apply_missing_parts` 倒序扫，后面的先插）。
#
# 两个标签的字面文字来自"结构部件"表的"插入文字"格：英文摘要那格写摘要
# 标签、英文关键词那格写关键词标签；旧预设只有英文摘要一格装两行（上行
# 摘要标签、下行关键词标签），`_english_labels()` 里保留了对旧写法的兼容。
# 两段内容都是论文的实质部分，没法自动生成，一律插占位提示。
ENGLISH_PLACEHOLDER_PROMPTS = {
    "英文题目": "［请在此处填写英文题目，全部使用大写字母］",
    # 跟中文副标题一样：副标题是论文的实质内容，没法自动生成，只能占个位、
    # 告诉用户"不要就整段删掉"（用户 2026-09-15 要做"完整的对称部件"）。
    "英文副标题": "［请在此处填写英文副标题］",
    "英文摘要": "［请在此处填写英文摘要内容，应当与中文摘要对应］",
    "英文关键词": "［请在此处填写 3～5 个英文关键词：用小写字母、不使用标点符号、每个之间空两格］",
}

# 引言/结论/参考文献/附录/致谢缺失时，标签下面那一整段内容占位语。
# 参考文献和附录额外把"序号怎么写"带上了——这两处的序号不是随便写的：
# 参考文献按 [1][2][3] 排（预设"引注"小节的"参考文献编号样式"就是这个写法，
# 真正的自动编号是阶段 3 的事，这里先给个提醒）；附录按规范 [226]
# "序号和题名之间空两格"。
ANCHOR_CONTENT_PROMPTS = {
    "引言": "［请在此处填写引言内容］",
    "结论": "［请在此处填写结论内容］",
    "参考文献": "［请在此处填写第 1 条参考文献；每条一段。已启用自动编号。］",
    "附录": "附录A  ［请在此处填写附录题名；序号和题名之间空两格］",
    "致谢": "［请在此处填写致谢内容］",
}

# 结构页"自动重新编号参考文献"**没勾**时用的参考文献占位语（用户 2026-09-15）：
# 那种情况下序号就是用户自己写的，提示语不能再声称"已经自动编号"。
REFERENCE_CONTENT_PROMPT_PLAIN = "［请在此处填写第 1 条参考文献；每条一段］"

# 附录比别的部件多一段：规范 [226] 要求"另起一行标注附录序号和题名"，但那
# 一句后面接着说"附录内容文字与图表编排样式可参照正文"——所以补附录时要给
# **两段**：一段"附录序号题名"（用 S20），再一段普通正文占位（用 S01）。
APPENDIX_BODY_PROMPT = "［请在此处填写附录内容；附录里的文字和图表格式参照正文］"

# ---------------------------------------------------------------- 认占位语
# 所有占位语的原文（工具插进去的就是这些字，一个字符都不差）。识别阶段拿它
# 判断"这行是不是我自己插的"。用户把占位语改过了（在方括号里打字），就不算
# 占位语了——那种情况按用户内容处理才是对的。
#
# **旧版占位语**（2026-09-20 改文案之前的写法）也要认：用旧版工具导出过的成品
# 再喂回来，里面躺的是旧文字；只认新文案的话，它们会被当成用户内容，
# 同时又补插一条新的。**以后改占位语文案，把被换掉的旧原文追加到这里，别删。**
LEGACY_PROMPTS: dict[str, tuple[str, ...]] = {
    "题目": ("［请在此处填写论文题目；题目一般不超过 20 个字］",),
    "副标题": ("［如不需要副标题，请把这一段整段删除］",),
    "摘要": ("［请在此处填写摘要内容：第三人称，300 字以内］",),
    # 2026-10-10 关键词改成与标签同段后，"前面的【关键词】已经写好"这半句不再成立。
    "关键词": ("［请在此处填写 3～5 个关键词，每个之间空两格；前面的【关键词】已经写好，正文里不用再打【】］",),
    "英文副标题": ("［如不需要英文副标题，请把这一段整段删除］",),
    "参考文献": ("［请在此处填写第 1 条参考文献；每条一段。序号已经是自动编号，"
                "回车接着写就会自己往下排，不用手打］",),
    "参考文献（不自动编号）": ("［请在此处填写第 1 条参考文献；每条一段，序号自己写］",),
}

ALL: frozenset[str] = frozenset(
    [*PLACEHOLDER_PROMPTS.values(), *CONTENT_PLACEHOLDER_PROMPTS.values(),
     *ENGLISH_PLACEHOLDER_PROMPTS.values(), *ANCHOR_CONTENT_PROMPTS.values(),
     REFERENCE_CONTENT_PROMPT_PLAIN, APPENDIX_BODY_PROMPT,
     *(t for texts in LEGACY_PROMPTS.values() for t in texts)]
)


def _is(text: str, current: str, legacy_key: str) -> bool:
    text = text.strip()
    return text == current or text in LEGACY_PROMPTS.get(legacy_key, ())


def is_placeholder(text: str) -> bool:
    """这段文字是不是**工具自己插的占位语**（原样、去掉首尾空白后比对）。"""
    return text.strip() in ALL


def is_english_title_placeholder(text: str) -> bool:
    """是不是"英文题目"那个占位语（＝英文题目的槽位就在这一段）。"""
    return _is(text, ENGLISH_PLACEHOLDER_PROMPTS["英文题目"], "英文题目")


def is_english_subtitle_placeholder(text: str) -> bool:
    """是不是"英文副标题"那个占位语（＝英文副标题的槽位就在这一段）。"""
    return _is(text, ENGLISH_PLACEHOLDER_PROMPTS["英文副标题"], "英文副标题")


def is_subtitle_placeholder(text: str) -> bool:
    """是不是"副标题"那个占位语（＝中文副标题的槽位就在这一段）。

    为什么要单独一个：中文副标题占位语以「］」结尾，而副标题的常规判据里
    有一条"不以标点结尾" ⇒ 识别端会把自巶己插的占位语判成"不是副标题" ⇒
    下一遍又插一条（AAT 产物层穷举 2026-09-17 抓到："body 内容整体复制"、
    "首段 run 包进未接受的修订"两条都是每遍 +1 段）。英文副标题那一边早就
    有这个口子（`is_english_subtitle_placeholder`），中文这条当时漏了。
    """
    return _is(text, PLACEHOLDER_PROMPTS["副标题"], "副标题")


def is_title_placeholder(text: str) -> bool:
    """是不是"题目"那个占位语（＝题目的槽位就在这一段）。

    跟副标题同一个道理：它同样以「］」结尾，过不了题目判据里"不以标点
    结尾"那一条 ⇒ 下一遍又当"没有题目"再插一条（AAT 2026-09-17：图表脚注
    测试那份稿子本来就没有中文题目，于是每遍稳定 +2 段：题目占位 + 副标题占位）。
    """
    return _is(text, PLACEHOLDER_PROMPTS["题目"], "题目")
